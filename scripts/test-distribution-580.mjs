/** Régressions de l'atelier distributif 5.8 et garde-fous de non-extrapolation. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {simulateSmic,simulatePensionAllowance,pensionAllowance} from '../dist/model-distribution-580.mjs';
const ctx={window:{}};vm.createContext(ctx);
vm.runInContext(fs.readFileSync(new URL('../dist/fiscal-individuel-570.js',import.meta.url),'utf8'),ctx);
const ir=ctx.window.ECOSIM_FISCAL_INDIVIDUEL_570.calculate;
const wage=(ratio,i,weight=1)=>({id:`w${i}`,hourlyGross:12.31*ratio,hoursPerYear:1607,weight});
const w=[1,1.05,1.2,2].map((r,i)=>wage(r,i));
const baseline=simulateSmic({currentSmicHourly:12.31,risePercent:0,workers:w});
assert.equal(baseline.totals.annualGrossPayDelta,0);
assert.equal(baseline.totals.mandatoryAffected,0);
const up=simulateSmic({currentSmicHourly:12.31,risePercent:10,workers:w});
assert.equal(up.totals.mandatoryAffected,2);
assert.equal(up.totals.spilloverAffected,0);
assert.ok(Math.abs(up.rows[0].hourlyAfter -12.31*1.1)<1e-9);
assert.ok(Math.abs(up.rows[1].hourlyAfter -12.31*1.1)<1e-9);
assert.equal(up.rows[2].annualGrossDelta,0);
assert.equal(up.rows[3].annualGrossDelta,0);
const weighted=simulateSmic({currentSmicHourly:12.31,risePercent:10,workers:[wage(1,0,10),wage(2,1,3)]});
assert.equal(weighted.totals.mandatoryAffected,10);
assert.equal(weighted.totals.weightedWorkers,13);
assert.ok(Math.abs(weighted.totals.annualGrossPayDelta-10*weighted.rows[0].annualGrossDelta)<1e-7);
const diffused=simulateSmic({currentSmicHourly:12.31,risePercent:10,workers:w,spilloverStrength:.25});
assert.equal(diffused.totals.mandatoryAffected,2);assert.equal(diffused.totals.spilloverAffected,2);
assert.ok(diffused.rows[2].indirectIncreaseHourly>diffused.rows[3].indirectIncreaseHourly);
const derog=simulateSmic({currentSmicHourly:12.31,risePercent:10,workers:[{...wage(.7,0),eligible:false}]});
assert.equal(derog.totals.annualGrossPayDelta,0);
assert.throws(()=>simulateSmic({currentSmicHourly:12.31,risePercent:0,workers:[wage(.9,0)]}),/sous le SMIC initial/);
assert.throws(()=>simulateSmic({currentSmicHourly:12.31,risePercent:10,workers:[wage(1,0),wage(1,0)]}),/dupliqué/);
assert.equal(pensionAllowance([15000]),1500);
assert.equal(pensionAllowance([1000]),454);
assert.equal(pensionAllowance([300]),300);
assert.equal(pensionAllowance([100000]),4439);
const households=[
  {id:'modeste',pensions:[12000],netTaxableIncome:10800,referenceTaxIncome:12000,weight:1,householdType:'single'},
  {id:'richer',pensions:[65000],netTaxableIncome:60561,referenceTaxIncome:70000,weight:2,householdType:'single'},
  {id:'small-pension-rich-household',pensions:[15000],netTaxableIncome:85000,referenceTaxIncome:90000,weight:1,householdType:'couple'}
];
const p=(reform)=>simulatePensionAllowance({households,reform,calculateIncomeTax:ir});
const threshold=55000;
const none=p({type:'remove_above_rfr',rfrThreshold:1000000});
assert.equal(none.totals.differenceImpot,0);
const abrupt=p({type:'remove_above_rfr',rfrThreshold:threshold});
assert.equal(abrupt.rows[0].taxDelta,0);
assert.ok(abrupt.rows[1].taxDelta>0);
assert.ok(abrupt.rows[2].taxDelta>0);
assert.equal(abrupt.rows[1].allowanceAfter,0);
const progressive=p({type:'phase_out_above_rfr',rfrThreshold:threshold,phaseOutWidth:25000});
assert.equal(progressive.rows[1].selectedFraction,.6);
assert.ok(progressive.rows[1].taxDelta>0&&progressive.rows[1].taxDelta<abrupt.rows[1].taxDelta);
const cap=p({type:'cap_above_rfr',rfrThreshold:threshold,newCap:3000});
assert.equal(cap.rows[1].allowanceAfter,3000);
assert.equal(cap.rows[2].allowanceAfter,1500);
assert.equal(cap.rows[2].taxDelta,0);
const onlyHighPensions=p({type:'remove_above_rfr',targetMetric:'pensions_total',rfrThreshold:55000});
assert.equal(onlyHighPensions.rows[1].selectedFraction,1);
assert.equal(onlyHighPensions.rows[2].selectedFraction,0,'RFR élevé et faible pension : ne pas sélectionner par pension');
assert.ok(onlyHighPensions.rows[2].targetMeasure===15000);
assert.throws(()=>p({type:'remove_above_rfr',targetMetric:'wealth',rfrThreshold:55000}),/ciblage/);
assert.throws(()=>p({type:'phase_out_above_rfr',rfrThreshold:0,phaseOutWidth:0}));
const html=fs.readFileSync(new URL('../dist/distribution-ciblee-580.html',import.meta.url),'utf8');
assert.match(html,/module" src="distribution-ciblee-580\.mjs"/);
assert.match(html,/aucun chiffrage national/i);
assert.doesNotMatch(html,/r[eé]sultats repr[eé]sentatifs de la France/i);
assert.match(fs.readFileSync(new URL('../dist/index.html',import.meta.url),'utf8'),/id="smic-distribution-link"/);
assert.match(fs.readFileSync(new URL('../dist/release-status-572.json',import.meta.url),'utf8'),/"distributionModuleVersion": "5\.8\.1"/);
console.log('ATELIER 5.8 OK : salaires légaux, diffusion facultative, cas fiscaux ciblés, poids, effets de seuil, garde-fous de publication.');
