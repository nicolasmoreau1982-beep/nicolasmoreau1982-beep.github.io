/** EcoSim 5.0 — alertes inter-moteurs (sans mutation de l'état). */
import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const ctx=vm.createContext({console,Map,Set,Object,Math,Number,Array,JSON});ctx.window=ctx;
for(const f of ['data.js','sectoral.js','quality-500.js'])vm.runInContext(fs.readFileSync(path.join(root,'dist',f),'utf8'),ctx,{filename:f});
const D=ctx.ECOSIM_DATA,S=ctx.ECOSIM_SECTORAL,Q=ctx.ECOSIM_QUALITY;
const defaults=()=>({changes:{},sectoral:[],engines:Object.fromEntries(Object.entries(D.policyEngines.controls).map(([k,v])=>[k,v.value])),structural:Object.fromEntries(Object.entries(D.structural.controls).map(([k,v])=>[k,v.value]))});
const inspect=s=>Q.inspect(s,{...D,sectoral:S});
let state=defaults();assert.equal(inspect(state).count,0);
const mk=(sector,instrument='credit')=>({sector,instrument,amountBn:2,startYear:2026,durationYears:5,response:'accounting'});
const verify=(make,code)=>{state=defaults();make(state);const before=JSON.stringify(state);const result=inspect(state);assert.ok(result.alerts.some(w=>w.code===code),code);assert.equal(JSON.stringify(state),before,'Le diagnostic ne doit rien modifier');};
verify(s=>{s.structural.renewables=20;s.sectoral=[mk('renewables')]},'enr');
verify(s=>{s.structural.nuclear=4;s.sectoral=[mk('nuclear')]},'nuclear');
verify(s=>{s.structural.efficiency=6;s.sectoral=[mk('building')]},'building');
verify(s=>{s.engines.transportInfrastructure=10;s.sectoral=[mk('transit')]},'transport');
verify(s=>{s.structural.carbonTax=20;s.sectoral=[mk('fossil','levy')]},'carbon');
verify(s=>{s.changes.R_IS=4;s.sectoral=[mk('metals','credit')]},'corporate-tax');
verify(s=>{s.engines.healthWorkforce=5;s.sectoral=[mk('health')]},'health');
verify(s=>{s.engines.childcarePlaces=10;s.changes.GF1004=3},'childcare');
verify(s=>{s.sectoral=[mk('renewables'),mk('renewables','grant')]},'same-sector-renewables');
state=defaults();state.sectoral=[mk('digital')];assert.equal(inspect(state).count,0);
assert.ok(inspect(defaults()).note.includes('aucune correction'));
const html=fs.readFileSync(path.join(root,'dist/index.html'),'utf8');
assert.ok(html.includes('id="qualite-500-list"'));assert.ok(html.includes('<script src="quality-500.js"></script>'));
const app=fs.readFileSync(path.join(root,'dist/app.js'),'utf8');assert.ok(app.includes('renderCrossModuleQuality500();'));
console.log('QUALITÉ 5.0 OK : 9 familles de recouvrements, absence de faux signalement simple, immutabilité, intégration HTML.');
