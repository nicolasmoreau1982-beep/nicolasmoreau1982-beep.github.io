/** 5.8.1 — schéma CSV, traçabilité non attestée, stratification, poids et export sans lignes individuelles. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {simulateSmic,simulatePensionAllowance} from '../dist/model-distribution-580.mjs';
import {parseCsv,loadWorkersCsv,loadHouseholdsCsv,checkedProvenance,diagnoseWeights,
 summarizeWageDistribution,summarizePensionDistribution,aggregatedExport} from '../dist/model-distribution-581.mjs';
const sourceW=fs.readFileSync(new URL('../dist/examples/distribution-salaires-581-exemple.csv',import.meta.url),'utf8');
const sourceP=fs.readFileSync(new URL('../dist/examples/distribution-foyers-581-exemple.csv',import.meta.url),'utf8');
const workers=loadWorkersCsv(sourceW),households=loadHouseholdsCsv(sourceP);
assert.equal(workers.length,5);assert.equal(households.length,4);
assert.equal(workers[0].hourlyGross,12.31);assert.equal(workers[4].eligible,false);
assert.deepEqual(households[3].pensions,[9000,9000]);
assert.equal(households[3].householdType,'couple');
assert.equal(parseCsv('id;description\n1;"texte ; et ""guillemets"""\n',['id','description'])[0].description,'texte ; et "guillemets"');
assert.deepEqual(parseCsv('\uFEFFid,description\r\n1,"hello, world"\r\n',['id','description']),[{id:'1',description:'hello, world'}]);
assert.throws(()=>parseCsv('id;x\n1;yes', ['id','description']),/Colonnes/);
assert.throws(()=>loadWorkersCsv(sourceW.replace('S02','S01')), /dupliqué/);
assert.throws(()=>loadWorkersCsv(sourceW.replace('S02;12,93','S02;-20')), /nombre décimal/);
assert.throws(()=>loadWorkersCsv(sourceW.replace('S02;12,93','S02;0')), /salaire|nombre|Salaire/i);
assert.throws(()=>loadWorkersCsv(sourceW.replace(';1;1\nS05', ';0;1\nS05')), /poids|Heures/i);
assert.throws(()=>loadWorkersCsv(sourceW.replace('S01','=HYPERLINK')), /Identifiant/);
assert.throws(()=>loadHouseholdsCsv(sourceP.replace('9000|9000','9000/9000')), /pensions/);
assert.throws(()=>loadHouseholdsCsv(sourceP.replace('couple','trois')), /householdType/);
assert.throws(()=>loadHouseholdsCsv(sourceP.replace('F03','F01')), /dupliqué/);
assert.throws(()=>loadHouseholdsCsv('id;pensions;netTaxableIncome;referenceTaxIncome;householdType;children;weight\nA;12000;10000;15000;single;0;0\n'),/Poids/);
assert.throws(()=>loadWorkersCsv(''),/CSV vide/);
assert.throws(()=>parseCsv('id;description\n1;"truncated',['id','description']), /non fermé/);
assert.throws(()=>parseCsv('id;description\n1;word;extra',['id','description']), /colonnes/);
assert.throws(()=>parseCsv('id;x\n'+'1;ok\n'.repeat(10001), ['id','x']),/Plus de 10000/);
const provenance=checkedProvenance({source:'Enquête fictive de démonstration',year:2026,coverage:'Salariés artificiels hors de toute enquête.'},'wage');
assert.equal(provenance.verifiedByEcoSim,false);
assert.equal(provenance.representativity,'NON_ETABLIE');
assert.throws(()=>checkedProvenance({source:'DARES',year:2026,coverage:'Court'},'wage'),/Provenance/);
const diag=diagnoseWeights([{weight:1},{weight:1},{weight:2}]);
assert.equal(diag.sumWeights,4);assert.ok(Math.abs(diag.effectiveSampleSize-8/3)<1e-12);
assert.equal(diag.maxWeightSharePercent,50);
assert.throws(()=>diagnoseWeights([{weight:0}]),/invalide/);
const wageReport=simulateSmic({currentSmicHourly:12.31,risePercent:10,workers});
const ws=summarizeWageDistribution(workers,wageReport);
assert.equal(ws.groups.length,6);
assert.equal(ws.groups.reduce((v,g)=>v+g.observations,0),workers.length);
assert.equal(ws.groups.reduce((v,g)=>v+g.weightedAffected,0),wageReport.totals.mandatoryAffected);
assert.ok(Math.abs(ws.groups.reduce((v,g)=>v+g.weightedDelta,0)-wageReport.totals.annualGrossPayDelta)<1e-7);
const wExport=aggregatedExport({kind:'smic',provenance,report:wageReport,summary:ws});
assert.equal(wExport.status,'REPRESENTATIVITE_NON_ETABLIE');
assert.ok(!JSON.stringify(wExport).includes('S01'),'Export agrégé sans ID');
assert.ok(!('rows' in wExport)&&!('workers' in wExport)&&!('input' in wExport));
const taxCtx={window:{}};vm.createContext(taxCtx);
vm.runInContext(fs.readFileSync(new URL('../dist/fiscal-individuel-570.js',import.meta.url),'utf8'),taxCtx);
const ir=taxCtx.window.ECOSIM_FISCAL_INDIVIDUEL_570.calculate;
const pensionReport=simulatePensionAllowance({households,reform:{type:'remove_above_rfr',rfrThreshold:55000},calculateIncomeTax:ir});
const ps=summarizePensionDistribution(households,pensionReport);
assert.equal(ps.groups.reduce((v,g)=>v+g.observations,0),households.length);
assert.equal(ps.groups.reduce((v,g)=>v+g.weightedAffected,0),pensionReport.totals.foyersAvecAbattementReduit);
assert.ok(Math.abs(ps.groups.reduce((v,g)=>v+g.weightedDelta,0)-pensionReport.totals.differenceImpot)<1e-7);
const pExport=aggregatedExport({kind:'pension',provenance:checkedProvenance({source:'Foyers fictifs',year:2025,coverage:'Profils artificiels fiscaux non anonymisation réelle.'},'pension'),report:pensionReport,summary:ps});
assert.ok(!JSON.stringify(pExport).includes('F01'),'Export fiscal agrégé sans ID');
assert.ok(!('households' in pExport)&&!('rows' in pExport));
assert.throws(()=>summarizeWageDistribution(workers.slice(1),wageReport),/incohérent/);
for(const file of ['dist/distribution-ciblee-580.html','dist/distribution-ciblee-580.mjs']){
 const s=fs.readFileSync(new URL('../'+file,import.meta.url),'utf8');
 assert.match(s,/distribution-581|distribution-ciblee-580|import-status/);
}
const html=fs.readFileSync(new URL('../dist/distribution-ciblee-580.html',import.meta.url),'utf8');
assert.match(html,/aucun chiffrage national/i);
assert.match(html,/sans envoi au serveur/i);
assert.match(html,/aucun nom, NIR/i);
assert.match(html,/s-csv-file/);assert.match(html,/p-csv-file/);
console.log('DISTRIBUTIONS 5.8.1 : CSV strict, traçabilité déclarée, pondérations Kish, ventilation, export agrégé sans données individuelles, tests de rejets OK.');
